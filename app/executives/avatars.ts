// Case-insensitive lookup map to ensure Linux/Vercel compatibility
const AVATAR_FILE_MAP = new Map<string, string>(
  EXECUTIVE_AVATAR_FILES.map((file) => [file.toLowerCase(), file])
);

/**
 * Checks whether a photo filename or path exists in public/executives/.
 * Returns the normalized exact path ("/executives/<exact-case-filename>") if found, or undefined.
 */
export function getAvailableExecutiveAvatar(fileNameOrPath: string): string | undefined {
  if (!fileNameOrPath) return undefined;
  const cleaned = fileNameOrPath.replace(/^\/?(executives\/)?/, "");
  const matched = AVATAR_FILE_MAP.get(cleaned.toLowerCase());
  return matched ? `/executives/${matched}` : undefined;
}
